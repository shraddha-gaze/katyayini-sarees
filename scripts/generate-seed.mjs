// Writes supabase/migrations/0002_seed.sql from src/data/catalogue.ts.
// Usage: node scripts/generate-seed.mjs   (Node 23.6+ runs the .ts import natively)
import { writeFileSync } from "node:fs";
import { categories, products } from "../src/data/catalogue.ts";

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;
const json = (o) => `${q(JSON.stringify(o))}::jsonb`;

const lines = ["-- Generated by scripts/generate-seed.mjs from src/data/catalogue.ts. Sample catalogue.", ""];

lines.push("insert into public.categories (slug, name, tagline, description, seo_title, seo_description, price_hint, featured, sort_order, art) values");
lines.push(
  categories
    .map(
      (c, i) =>
        `  (${q(c.slug)}, ${q(c.name)}, ${q(c.tagline)}, ${q(c.description)}, ${q(c.seoTitle)}, ${q(c.seoDescription)}, ${q(c.priceHint)}, ${c.featured}, ${i}, ${json(c.art)})`,
    )
    .join(",\n") + "\non conflict (slug) do nothing;",
);
lines.push("");

lines.push(
  "insert into public.products (id, slug, name, category_slug, colour, price, mrp, stock, fabric, zari, weave, occasions, weight_grams, description, care, has_blouse_piece, badge, featured, images, art, created_at) values",
);
lines.push(
  products
    .map(
      (p) =>
        `  (${q(p.id)}, ${q(p.slug)}, ${q(p.name)}, ${q(p.category)}, ${q(p.colour)}, ${p.price}, ${p.mrp}, ${p.stock}, ${q(p.fabric)}, ${q(p.zari)}, ${q(p.weave)}, ${arr(p.occasions)}, ${p.weightGrams}, ${q(p.description)}, ${q(p.care)}, ${p.hasBlousePiece}, ${q(p.badge)}, ${p.featured}, ${arr(p.images)}, ${json(p.art)}, ${q(p.createdAt)})`,
    )
    .join(",\n") + "\non conflict (id) do nothing;",
);
lines.push("");

writeFileSync(new URL("../supabase/migrations/0002_seed.sql", import.meta.url), lines.join("\n"));
console.log(`Wrote ${categories.length} categories and ${products.length} products`);
